function stateJson(state: ExpeditionState): string {
  return JSON.stringify(state);
}

function expectInputUnchanged(
  state: ExpeditionState,
  transition: (input: ExpeditionState) => unknown
) {
  const before = stateJson(state);
  transition(state);
  expect(stateJson(state)).toBe(before);
}

