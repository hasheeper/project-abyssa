import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const tokens = JSON.parse(readFileSync(resolve(root, "src/shared/ui/motion/tokens.json"), "utf8"));
const board = tokens.pageBoard;
const manor = tokens.manorWindow;
const css = `/* Generated by scripts/sync-motion-tokens.mjs. Edit motion/tokens.json. */
:root, [data-ui-motion="full"] {
  --abyssa-motion-ease: cubic-bezier(${tokens.ease.join(", ")});
  --abyssa-motion-hover: ${tokens.control.hoverMs}ms;
  --abyssa-motion-press: ${tokens.control.pressMs}ms;
  --abyssa-motion-press-distance: ${tokens.control.pressPx}px;
}

[data-ui-motion="reduced"] {
  --abyssa-motion-hover: 0ms;
  --abyssa-motion-press: 0ms;
  --abyssa-motion-press-distance: 0px;
}

@media (prefers-reduced-motion: reduce) {
  :root, [data-ui-motion="full"] {
    --abyssa-motion-hover: 0ms;
    --abyssa-motion-press: 0ms;
    --abyssa-motion-press-distance: 0px;
  }
}
`;
// Separate CSS entries keep unused presets out of page-local style packs.
// Motion reads the same JSON in presets.ts; CSS is generated in milliseconds.
const outputs = {
  "styles/motion-tokens.css": css,
  "motion/page-board.css": `/* Generated by scripts/sync-motion-tokens.mjs. Edit motion/tokens.json.
   Apply the preset to an existing board; readiness and child timing stay local. */
:root, [data-ui-motion="full"] {
  --abyssa-motion-page-board-enter: abyssa-page-board-settle ${board.settleMs}ms cubic-bezier(${board.settleEase.join(", ")}) both,
    abyssa-ui-appear ${board.appearMs}ms cubic-bezier(${board.appearEase.join(", ")}) both;
}
[data-ui-motion="reduced"] { --abyssa-motion-page-board-enter: none; }
@media (prefers-reduced-motion: reduce) {
  :root, [data-ui-motion="full"] { --abyssa-motion-page-board-enter: none; }
}
@keyframes abyssa-page-board-settle {
  from { translate: 0 -${board.distancePx}px; }
  to { translate: 0 0; }
}
@keyframes abyssa-ui-appear {
  from { opacity: 0; }
  to { opacity: 1; }
}
`,
  "motion/modal-tokens.css": `/* Generated by scripts/sync-motion-tokens.mjs. Edit motion/tokens.json. */
.abyssa-modal[data-ui-motion-preset="manor"] {
  --abyssa-motion-manor-body-enter: manor-window-contents-in ${manor.bodyMs}ms ${manor.bodyDelayMs}ms cubic-bezier(${manor.contentEase.join(", ")}) backwards;
  --abyssa-motion-manor-chrome-enter: manor-window-contents-in ${manor.chromeMs}ms ${manor.chromeDelayMs}ms cubic-bezier(${manor.contentEase.join(", ")}) backwards;
  --abyssa-motion-manor-content-distance: ${manor.contentDistancePx}px;
}
`,
};
for (const [path, content] of Object.entries(outputs)) {
  const output = resolve(root, "src/shared/ui", path);
  if (process.argv.includes("--write")) writeFileSync(output, content);
  else if (readFileSync(output, "utf8") !== content) {
    console.error(`Motion CSS tokens are stale: ${path}. Run npm run motion:tokens.`);
    process.exitCode = 1;
  }
}
if (!process.exitCode) console.log("Motion TS/CSS tokens are in sync (controls, page-board, manor).");
